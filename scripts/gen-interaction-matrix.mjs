// Regenerates `lib/zero/interaction-matrix-doc.ts` from the git-tracked canonical doc
// `docs/interaction-matrix.md`, so the /matrix-interactions web viewer renders it with
// ZERO copy-drift — the .md is the single source of truth.
//
// WHY a build step (not a runtime read): the page is a client component using
// react-markdown, and the desktop build is a static export (`output: 'export'`), so there's
// no server to `fs.readFile` the .md at request time. Inlining it into a .ts the bundler can
// see works uniformly for web dev, web build, and the static desktop export. (The memory
// doc under v0_memories/ is NOT usable here — that store isn't on the code filesystem.)
//
// Run via `pnpm gen:docs`, or automatically through the `predev` / `prebuild` hooks. If the
// source is somehow missing, keep the committed .ts (exit 0) rather than clobbering it.

import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const SRC = join(ROOT, "docs/interaction-matrix.md")
const OUT = join(ROOT, "lib/zero/interaction-matrix-doc.ts")

if (!existsSync(SRC)) {
  console.log(`[gen-matrix] source not found (${SRC}); keeping committed ${OUT}`)
  process.exit(0)
}

const md = readFileSync(SRC, "utf8")

// JSON.stringify yields a valid double-quoted JS string literal with all escaping handled
// (newlines → \n, quotes escaped). Backticks pass through literally, so — unlike the old
// hand-written String.raw template — there's no backtick-terminates-the-literal hazard.
const header = `/**
 * AUTO-GENERATED — DO NOT EDIT BY HAND.
 * Source of truth: docs/interaction-matrix.md
 * Regenerated by scripts/gen-interaction-matrix.mjs via the predev / prebuild hooks.
 *
 * This file inlines the canonical markdown so the /matrix-interactions web viewer can
 * render it (the page is a static/client component with no runtime fs). Edit the .md,
 * not this file — it will be overwritten on the next dev/build.
 */
`
const body = `export const INTERACTION_MATRIX_MD = ${JSON.stringify(md)}\n`

writeFileSync(OUT, header + body)
console.log(`[gen-matrix] wrote ${OUT} (${md.length} chars from ${SRC})`)
